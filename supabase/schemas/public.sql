CREATE TYPE public.tracklist_version AS ENUM(
    'full',
    'expanded',
    'mixtape',
    'base'
);

CREATE TABLE public.challenge_attempts(
    id integer GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    name text NOT NULL,
    phone text NOT NULL,
    ip inet NOT NULL DEFAULT inet_client_addr(),
    answer integer NOT NULL,
    created_at timestamp with time zone NOT NULL DEFAULT now(),
    CONSTRAINT challenge_attempts_pkey PRIMARY KEY (id),
    CONSTRAINT challenge_attempts_answer_check CHECK ((answer >= 0))
);

CREATE TABLE public.contributors(
    id integer GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    name text NOT NULL,
    email text NULL,
    amount integer NOT NULL,
    user_id uuid NULL,
    rewards_claimed boolean NOT NULL DEFAULT FALSE,
    CONSTRAINT contributors_pkey PRIMARY KEY (id),
    CONSTRAINT contributors_email_key UNIQUE (email),
    CONSTRAINT contributors_user_id_fkey FOREIGN KEY (user_id) REFERENCES auth.users(id) ON UPDATE CASCADE ON DELETE RESTRICT
);

CREATE TABLE public.credits(
    key text NOT NULL,
    name text NOT NULL,
    CONSTRAINT credits_pkey PRIMARY KEY (key)
);

CREATE TABLE public.tracks(
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    title text NOT NULL,
    filename text NOT NULL,
    runtime bigint NOT NULL,
    style text[] NOT NULL,
    missing_from tracklist_version[] NULL,
    CONSTRAINT tracks_pkey PRIMARY KEY (id)
);

CREATE VIEW public.contributor_names AS
SELECT
    name,
    CASE WHEN amount >= 1000
        AND amount <= 1999 THEN
        'bronze'
    WHEN amount >= 2000
        AND amount <= 3499 THEN
        'silver'
    WHEN amount >= 3500
        AND amount <= 4999 THEN
        'gold'
    WHEN amount >= 5000
        AND amount <= 49999 THEN
        'platinum'
    WHEN amount >= 50000 THEN
        'executive'
    END AS tier
FROM
    public.contributors
WHERE
    amount >= 1000;

CREATE POLICY "Enable read access based on user ID" ON public.contributors AS permissive
    FOR SELECT TO authenticated
        USING ((
            SELECT
                auth.uid()) = user_id);

CREATE POLICY "Enable update access based on user ID" ON public.contributors AS permissive
    FOR UPDATE TO authenticated
        USING ((
            SELECT
                auth.uid()) = user_id)
            WITH CHECK ((
                SELECT
                    auth.uid()) = user_id);

CREATE POLICY "Enable read access for all users" ON public.credits AS permissive
    FOR SELECT TO public
        USING (TRUE);

CREATE POLICY "Enable read access for all users" ON public.tracks AS permissive
    FOR SELECT TO public
        USING (TRUE);

CREATE POLICY "Enable create access for unauthenticated users" ON public.challenge_attempts AS permissive
    FOR INSERT TO public
        WITH CHECK (TRUE);

ALTER TABLE public.challenge_attempts ENABLE ROW LEVEL SECURITY;

ALTER TABLE public.contributors ENABLE ROW LEVEL SECURITY;

ALTER TABLE public.credits ENABLE ROW LEVEL SECURITY;

ALTER TABLE public.tracks ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Allow authenticated users to access rewards" ON storage.objects
    FOR SELECT TO authenticated
        USING (bucket_id = 'rewards'
            AND ((name LIKE 'm4a/%' or name LIKE 'mp3/%' or name LIKE 'wav/%') OR (name LIKE 'mp4/%.mp4' AND replace(name, 'mp4/', '') =(
                SELECT
                    id::text || '.mp4'
                FROM
                    public.contributors
                WHERE
                    user_id = auth.uid()))));
